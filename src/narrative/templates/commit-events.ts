// ── 工具函数：按阵营取模板 ────────────────────────────────────

export function pickTemplate(
  bank:    TemplateBank,
  faction: FactionKey
): string {
  const pool = bank[faction] ?? bank.orthodox;
  return pool[Math.floor(Math.random() * pool.length)];
}
